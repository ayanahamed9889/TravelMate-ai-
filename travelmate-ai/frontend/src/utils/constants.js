export function cityToIata(name) {
  const q = (name || "").trim().toLowerCase();
  if (!q) return "";
  if (CITY_TO_IATA[q]) return CITY_TO_IATA[q];
  // "Kyoto, Japan" / "Paris France": match a whole known city name inside the text (longest first)
  const hit = Object.keys(CITY_TO_IATA)
    .sort((a, b) => b.length - a.length)
    .find((k) => new RegExp(`(^|[^a-z])${k.replace(/[-.*+?^${}()|[\]\\]/g, "\\$&")}($|[^a-z])`).test(q));
  return hit ? CITY_TO_IATA[hit] : "";
}
